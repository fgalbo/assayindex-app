const aliasOwners = new Map<string, number>();
QUERY_RULES.forEach((rule, ruleIndex) => {
  const ruleAliases = new Set(rule.aliases.flatMap((alias) => [alias, alias.replaceAll(" ", "")]));
  for (const alias of ruleAliases) {
    const existingOwner = aliasOwners.get(alias);
    if (existingOwner !== undefined && existingOwner !== ruleIndex) {
      throw new Error(`Duplicate common-order query alias ${alias}.`);
    }
    aliasOwners.set(alias, ruleIndex);
  }
});

export function resolveCommonLabOrderQueryInterpretation(
  rawQuery: string,
  normalizedQuery: string,
  compactQuery: string,
) {
  const rule = QUERY_RULES.find(({ aliases }) =>
    aliases.some((alias) => alias === normalizedQuery || alias === compactQuery));
  if (!rule) return null;
  if (rule.excludedRawAliases?.includes(rawQuery.trim())) return null;

  return {
    targetLoincCodes: rule.targetLoincCodes,
    publicInterpretation: {
      interpretationType: "assayindex-search-heuristic",
      label: rule.label,
      evidenceLabel: rule.evidenceLabel,
      evidenceUrl: rule.evidenceUrl,
      ambiguityNote: rule.ambiguityNote,
    } satisfies CommonLabOrderQueryInterpretation,
  };
}
