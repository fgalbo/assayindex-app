function supplementCodes(conceptId: string) {
  const concept = mnemonicSupplement.concepts.find((candidate) => candidate.id === conceptId);
  if (!concept) throw new Error(`Unknown common mnemonic supplement concept ${conceptId}.`);
  return concept.loincCodes;
}

